REST API for managing products with multi-currency prices. 7 endpoints under `/api/v1`.

## Authentication

There is no login: every endpoint requires `Authorization: Bearer <token>` (Laravel Sanctum).

- **Demo tokens.** `php artisan migrate --seed` creates one token for `admin@example.com` and one for `viewer@example.com` from `DEMO_ADMIN_TOKEN` and `DEMO_VIEWER_TOKEN` (see `.env.example`). The value to send is `{id}|{secret}`; on a freshly seeded database the ids are `1` (admin) and `2` (viewer). The seeder prints the full values. They are not created with `APP_ENV=production`.
- **Your own tokens.** `php artisan api:token {email} {--name=}` issues a new token with the abilities of the user role and prints its full value. It expires after 8 h (`API_TOKEN_TTL_MINUTES`); demo tokens never expire.
- **Roles.** `admin` (abilities `products:read` and `products:write`) and `viewer` (only `products:read`; writes return 403).

In "Try it", paste the full token in the Bearer scheme.

## Error format

Every error has the same body: `message` (English, fixed per code), `code` (stable, use it in clients), `errors` (only on 422) and `request_id` (same as the `X-Request-Id` header).

| HTTP | code |
|---|---|
| 400 | `bad_request` |
| 401 | `unauthenticated` |
| 403 | `forbidden` |
| 404 | `not_found` |
| 405 | `method_not_allowed` |
| 409 | `conflict` |
| 413 | `payload_too_large` |
| 422 | `validation_error` |
| 429 | `too_many_requests` |
| 500 | `server_error` |

Evaluation order: 401, 403/404, 422, 409.

## Conventions

- Amounts are decimal strings (`"19.99"`); `exchange_rate` has 6 decimals. Input accepts a string or a number with up to 2 decimals.
- Dates are ISO 8601 UTC.
- There is no currency endpoint: ids come from the seeder (on a freshly seeded database: USD 1, EUR 2, GBP 3, COP 4, MXN 5). Every product returns its base currency embedded.
- Default rate limit: 60 requests per minute per user, configurable (`X-RateLimit-*` and `Retry-After` headers).
- `PUT` replaces the whole resource; `PATCH` is not supported.
MD,
